// Free text from the catalogue (region display names) is normalised: no
// double dashes, em-dashes or en-dashes in published prose (project writing rules),
// and no pipe characters that would break a table cell.
function clean(s) {
  return String(s ?? '')
    .replace(/\s*--\s*/g, ', ')
    .replace(/\u{2014}/gu, ',')
    .replace(/\u{2013}/gu, '-')
    .replace(/\|/g, '/')
    .replace(/</g, '(').replace(/>/g, ')')
    .trim();
}

const code = (s) => `\`${s}\``;

function countryName(c, lang) {
  const e = COUNTRY[c];
  return e ? e[L[lang]] : c;
}

function residencyCell(c, lang) {
  if (c === 'OPERATOR_SITE' || c === 'UNKNOWN') return `${countryName(c, lang)} (${code(c)})`;
  return `${countryName(c, lang)} (${c})`;
}

function jurisdictionLabel(j, lang) {
  const e = JURISDICTION[j];
  return e ? `${e[L[lang]]} (${code(j)})` : code(j);
}

function exposureLabel(list, lang) {
  if (!list || list.length === 0) return T[lang].none;
  return list.map((x) => (EXPOSURE[x] ? `${EXPOSURE[x][L[lang]]} (${code(x)})` : code(x))).join(', ');
}

function exposureShort(list, lang) {
  if (!list || list.length === 0) return lang === 'en' ? 'none' : 'keine';
  return list.map((x) => (EXPOSURE[x] ? EXPOSURE[x][L[lang]] : x)).join(', ');
}

function displayName(provider, meta, lang) {
  if (DISPLAY[provider]) return DISPLAY[provider][lang];
  return clean(String(meta.name ?? provider).replace(/\s*service catalogue/i, ''));
}

function residencyOf(r) {
  return String(r.sovereignty?.residency_country ?? r.country ?? 'UNKNOWN').toUpperCase() || 'UNKNOWN';
}

function loadCatalogues() {
  return readdirSync(CATALOGUE_DIR)
    .filter(isProviderCatalogueFile)
    .map((file) => {
      const provider = file.replace(/\.json$/, '');
      const raw = JSON.parse(readFileSync(join(CATALOGUE_DIR, file), 'utf8'));
      return { provider, file, meta: raw.meta ?? {}, regions: Array.isArray(raw.regions) ? raw.regions : [] };
    })
    .sort((a, b) => a.provider.localeCompare(b.provider));
}

function summarise(cat, geo) {
  const { regions } = cat;
  const distinct = new Set();
  for (const r of regions) for (const s of r.services ?? []) if (s && s.code) distinct.add(s.code);
  const jurisdictions = [...new Set(regions.map((r) => r.sovereignty?.operator_jurisdiction).filter(Boolean))];
  const certs = new Map();
  for (const r of regions) for (const c of r.sovereignty?.certifications ?? []) {
    if (!certs.has(c)) certs.set(c, []);
    certs.get(c).push(r.id);
  }
  const defEurope = geo.lzGeographyDefaultRegion('europe', regions);
  const defGermany = geo.lzGeographyDefaultRegion('germany', regions);
  const automated = UPDATE_PROVIDERS.has(cat.provider);
  return { distinct: distinct.size, jurisdictions, certs, defEurope, defGermany, automated };
}

function jurisdictionSummary(cat, lang) {
  // Group regions by (jurisdiction, exposure) so mixed catalogues (OCI) read clearly.
  const groups = new Map();
  for (const r of cat.regions) {
    const j = r.sovereignty?.operator_jurisdiction ?? 'UNKNOWN';
    const ex = (r.sovereignty?.extraterritorial_exposure ?? []).join('+');
    const key = `${j}|${ex}`;
    if (!groups.has(key)) groups.set(key, { j, ex: r.sovereignty?.extraterritorial_exposure ?? [], ids: [] });
    groups.get(key).ids.push(r.id);
  }
  return [...groups.values()];
}

function regionRow(r, lang, geo, showName) {
  const s = r.sovereignty ?? {};
  const geos = geo.lzRegionGeographies(r);
  const cells = [
    code(r.id),
    ...(showName ? [clean(r.display) || '-'] : []),
    residencyCell(residencyOf(r), lang),
    jurisdictionLabel(s.operator_jurisdiction, lang),
    exposureShort(s.extraterritorial_exposure, lang),
    (s.certifications ?? []).length ? s.certifications.map(code).join(', ') : T[lang].none,
    String((r.services ?? []).length),
    geos.length ? geos.map(code).join(', ') : '-',
  ];
  return `| ${cells.join(' | ')} |`;
}

function regionHeader(lang, showName) {
  const t = T[lang];
  const cols = [t.regionId, ...(showName ? [t.name] : []), t.residency, t.jurisdiction, t.exposure, t.certTable, t.servicesCol, t.geos];
  return `| ${cols.join(' | ')} |\n|${cols.map(() => '---').join('|')}|`;
}

const MANY = 12;

function pageFacts(cat, lang, geo) {
  const t = T[lang];
  const sum = summarise(cat, geo);
  const { meta, regions, provider } = cat;
  const n = regions.length;
  const out = [];

  // Summary table
  const jGroups = jurisdictionSummary(cat, lang);
  const byJ = new Map();
  for (const g of jGroups) byJ.set(g.j, [...(byJ.get(g.j) ?? []), ...g.ids]);
  const jurCell = byJ.size === 1
    ? jurisdictionLabel(jGroups[0].j, lang)
    : t.mixed([...byJ.entries()].map(([j, ids]) => `${jurisdictionLabel(j, lang)}: ${ids.map(code).join(', ')}`));
  const exCell = jGroups.length === 1
    ? exposureLabel(jGroups[0].ex, lang)
    : t.mixed(jGroups.map((g) => `${g.ids.map(code).join(', ')}: ${exposureLabel(g.ex, lang)}`));
  const certCell = sum.certs.size === 0
    ? t.none
    : [...sum.certs.entries()].sort((a, b) => a[0].localeCompare(b[0])).map(([c, ids]) => `${code(c)} (${ids.length} ${ids.length === 1 ? t.region : t.regionsWord})`).join(', ');
  const mode = meta.source?.mode;
  const src = SOURCE_LABEL[mode]?.[lang] ?? (lang === 'en' ? 'the provider\'s public sources' : 'die öffentlichen Quellen des Anbieters');
  const refreshCell = sum.automated ? t.automated(provider, src) : t.curated;
  const conf = CONFIDENCE[meta.confidence]?.[L[lang]] ?? String(meta.confidence ?? '-');
  const def = (id) => (id ? code(`${provider}:${id}`) : t.noGeo);

  out.push(`## ${t.summary}`, '');
  out.push(`| ${t.property} | ${t.value} |`, '|---|---|');
  out.push(`| ${t.providerId} | ${code(provider)} |`);
  out.push(`| ${t.catName} | ${clean(meta.name)} |`);
  out.push(`| ${t.regions} | ${n} |`);
  out.push(`| ${t.services} | ${sum.distinct} |`);
  out.push(`| ${t.jurisdiction} | ${jurCell} |`);
  out.push(`| ${t.exposure} | ${exCell} |`);
  out.push(`| ${t.certs} | ${certCell} |`);
  out.push(`| ${t.refresh} | ${refreshCell} |`);
  out.push(`| ${t.confidence} | ${conf} |`);
  out.push(`| ${t.updated} | ${clean(meta.last_updated)} |`);
  out.push(`| ${t.schema} | ${clean(meta.schema_version)} |`);
  out.push(`| ${t.defEurope} | ${def(sum.defEurope)} |`);
  out.push(`| ${t.defGermany} | ${def(sum.defGermany)} |`);
  out.push(`| ${t.source} | [lz-catalogues/${cat.file}](https://github.com/Accenture/SWAO/blob/main/lz-catalogues/${cat.file}) |`);
  out.push('');

  // Regions
  const showName = regions.some((r) => r.display);
  if (n <= MANY) {
    out.push(`## ${t.regionTable}`, '', t.allListed(n), '');
    out.push(regionHeader(lang, showName));
    for (const r of regions) out.push(regionRow(r, lang, geo, showName));
    out.push('');
  } else {
    const europe = regions.filter((r) => geo.lzRegionGeographies(r).includes('europe'))
      .sort((a, b) => a.id.localeCompare(b.id));
    out.push(`## ${t.regionTable}`, '', t.manyNote(n, europe.length), '');
    out.push(`### ${t.byCountry}`, '');
    out.push(`| ${t.country} | ${t.regions} | ${t.ids} |`, '|---|---|---|');
    const byC = new Map();
    for (const r of regions) {
      const c = residencyOf(r);
      if (!byC.has(c)) byC.set(c, []);
      byC.get(c).push(r.id);
    }
    const rows = [...byC.entries()].sort((a, b) => {
      const special = (c) => (c === 'UNKNOWN' || c === 'OPERATOR_SITE' ? 1 : 0);
      return special(a[0]) - special(b[0]) || countryName(a[0], lang).localeCompare(countryName(b[0], lang), lang);
    });
    for (const [c, ids] of rows) out.push(`| ${residencyCell(c, lang)} | ${ids.length} | ${ids.sort().map(code).join(', ')} |`);
    out.push('');
    if (byC.has('UNKNOWN')) out.push(t.unknownNote, '');
    out.push(`### ${t.europeTable}`, '');
    out.push(regionHeader(lang, showName));
    for (const r of europe) out.push(regionRow(r, lang, geo, showName));
    out.push('');
  }

  // Certifications
  out.push(`## ${t.certTable}`, '');
  if (sum.certs.size === 0) {
    out.push(t.noCerts, '');
  } else {
    out.push(`| ${t.cert} | ${t.certRegions} |`, '|---|---|');
    for (const [c, ids] of [...sum.certs.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
      const list = ids.length > MANY ? `${ids.length} ${t.regionsWord}` : ids.map(code).join(', ');
      out.push(`| ${code(c)} | ${list} |`);
    }
    out.push('', t.certNote, '');
  }

  // Using
  const example = `${provider}:${sum.defEurope ?? regions[0]?.id ?? 'region'}`;
  out.push(`## ${t.using}`, '', t.usingText(provider, example), '');
  if (sum.defEurope) out.push(t.usingGeo(provider), '');
  out.push(t.usingCopy(provider), '', t.limits, '');
  out.push(`## ${t.related}`, '', t.relatedList);
  return out.join('\n');
}

function indexFacts(cats, lang, geo) {
  const t = T[lang];
  const out = [];
  out.push(`| ${t.idxCatalogue} | ${t.idxProvider} | ${t.idxJur} | ${t.idxRegions} | ${t.idxRefresh} | ${t.idxConf} | ${t.idxUpdated} |`);
  out.push('|---|---|---|---|---|---|---|');
  for (const cat of cats) {
    const sum = summarise(cat, geo);
    const jur = [...new Set(cat.regions.map((r) => r.sovereignty?.operator_jurisdiction).filter(Boolean))]
      .map((j) => (JURISDICTION[j] ? JURISDICTION[j][L[lang]].split(',')[0] : j)).join(', ');
    const conf = CONFIDENCE[cat.meta.confidence]?.[L[lang]] ?? String(cat.meta.confidence ?? '-');
    out.push(`| [${displayName(cat.provider, cat.meta, lang)}](${t.prefix}/lz-catalogues/${cat.provider}) | ${code(cat.provider)} | ${jur} | ${cat.regions.length} | ${sum.automated ? t.idxAutomated : t.idxCurated} | ${conf} | ${clean(cat.meta.last_updated)} |`);
  }
  return out.join('\n');
}

function splice(existing, facts, file) {
  const a = existing.indexOf(START);
  const b = existing.indexOf(END);
  if (a < 0 || b < a) throw new Error(`${file}: marker comments missing; add ${START} and ${END}`);
  return `${existing.slice(0, a)}${START}\n\n${facts}\n\n${existing.slice(b)}`;
}

function newPage(cat, lang, facts) {
  const t = T[lang];
  return `# ${displayName(cat.provider, cat.meta, lang)} (${cat.provider})\n\n${t.placeholder}\n\n${START}\n\n${facts}\n\n${END}\n`;
}

async function main() {
  const geo = await import(pathToFileURL(GEO_SRC).href);
  const cats = loadCatalogues();
  let stale = 0;
  const write = (path, content) => {
    const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
    if (current === content) return;
    stale++;
    if (CHECK) { console.error(`[stale] ${path}`); return; }
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content, 'utf8');
    console.log(`  wrote ${path}`);
  };
  for (const [lang, dir] of [['en', DOCS_EN], ['de', DOCS_DE]]) {
    for (const cat of cats) {
      const path = join(dir, `${cat.provider}.md`);
      const facts = pageFacts(cat, lang, geo);
      write(path, existsSync(path) ? splice(readFileSync(path, 'utf8'), facts, path) : newPage(cat, lang, facts));
    }
    const idx = join(dir, 'index.md');
    if (!existsSync(idx)) throw new Error(`${idx} missing; write the overview page with the marker comments first`);
    write(idx, splice(readFileSync(idx, 'utf8'), indexFacts(cats, lang, geo), idx));
  }
  if (CHECK && stale > 0) {
    console.error(`[FAIL] ${stale} Landing Zone catalogue page(s) out of date; run node swao/docs-site/scripts/generate-lz-catalogue-pages.mjs`);
    process.exit(1);
  }
  console.log(`[ok] Landing Zone catalogue pages: ${cats.length} catalogues, ${stale} file(s) ${CHECK ? 'stale' : 'updated'}.`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch((err) => { console.error(err instanceof Error ? err.message : String(err)); process.exit(1); });
}
