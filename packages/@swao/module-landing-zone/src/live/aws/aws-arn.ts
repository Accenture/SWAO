// #3801: ARN -> service, region and resource type, never a resource name
// (Design 120 section 6.4). The resource type comes from the ARN formats of
// the AWS Service Authorization Reference (aws-arn-formats.ts, generated by
// scripts/refresh-aws-arn-formats.mjs): the format whose literal text matches
// the ARN's resource part best names the type, for example `bucket` for
// `arn:aws:s3:::<BucketName>`, `topic` for SNS, `queue` for SQS, `pipeline` /
// `stage` / `action` for CodePipeline, `log-group` for CloudWatch Logs,
// `secret` for Secrets Manager. The old rule took the text before the first
// `/`, which for ARNs without a type prefix (or with a `:` before the `/`) is
// the resource name. When no format matches, the type is a literal type token
// of the service's formats when the ARN starts with one, else `resource`.
// Placeholders match `[^/:]+`, the last one `.+`, so a match is linear.
//
// #3851: the Reference lacks some ARN shapes that live scans return, and it
// names some kinds per variant. AWS_ARN_SUPPLEMENT adds the missing formats
// (Service Catalog provisioned products, `stack/<name>/<id>`, seen live on
// 2026-11-04) and AWS_TYPE_ALIASES folds variants into one kind (EventBridge
// rules on the default and on custom buses are both `rule`). Both tables are
// hand-maintained next to the generated one; see
// scripts/refresh-aws-arn-formats.mjs.

import { AWS_ARN_FORMATS } from './aws-arn-formats.js';

interface CompiledFormat { type: string; re: RegExp; literal: number }

const escapeRe = (s: string): string => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const normType = (name: string): string => name.trim().toLowerCase().replace(/\s+/g, '-');

function compile(type: string, resource: string): CompiledFormat {
  const parts = resource.split(/(\$\{[A-Za-z0-9]+\})/);
  const last = parts.reduce((i, p, k) => (/^\$\{/.test(p) ? k : i), -1);
  let re = '^';
  let literal = 0;
  let prevPlaceholder = false;
  parts.forEach((p, k) => {
    if (p === '') return;
    if (/^\$\{[A-Za-z0-9]+\}$/.test(p)) {
      // Adjacent placeholders (`${A}${B}`) are one run, so no two quantifiers meet.
      if (!prevPlaceholder) re += k === last ? '.+' : '[^/:]+';
      else if (k === last) re = `${re.slice(0, -'[^/:]+'.length)}.+`;
      prevPlaceholder = true;
      return;
    }
    prevPlaceholder = false;
    re += escapeRe(p);
    literal += p.length;
  });
  return { type: normType(type), re: new RegExp(`${re}$`), literal };
}

/** #3851: ARN formats missing from the Service Authorization Reference: service -> [type, resource part]. */
export const AWS_ARN_SUPPLEMENT: Readonly<Record<string, readonly (readonly [string, string])[]>> = {
  servicecatalog: [['stack', 'stack/${ProvisionedProductName}/${ProvisionedProductId}']],
};

/** #3851: one kind per resource: service -> Reference type -> type reported. */
export const AWS_TYPE_ALIASES: Readonly<Record<string, Readonly<Record<string, string>>>> = {
  events: { 'rule-on-default-event-bus': 'rule', 'rule-on-custom-event-bus': 'rule' },
};

const formatTable = (service: string): readonly (readonly [string, string])[] => [...(AWS_ARN_FORMATS[service] ?? []), ...(AWS_ARN_SUPPLEMENT[service] ?? [])];

const compiled = new Map<string, CompiledFormat[]>();
function formatsOf(service: string): CompiledFormat[] {
  let c = compiled.get(service);
  if (!c) {
    c = formatTable(service).map(([t, r]) => compile(t, r)).sort((a, b) => b.literal - a.literal);
    compiled.set(service, c);
  }
  return c;
}

/** Literal type tokens a service's ARN formats start with (`function`, `log-group`, `instance`, ...). */
function literalTypeTokens(service: string): Set<string> {
  const out = new Set<string>();
  for (const [, r] of formatTable(service)) {
    const m = /^([A-Za-z][A-Za-z0-9-]*)[/:]/.exec(r);
    if (m) out.add((m[1] as string).toLowerCase());
  }
  return out;
}

/** Resource type of an ARN resource part for a service; never a name. */
export function awsResourceType(service: string, resource: string): string {
  const alias = (t: string): string => AWS_TYPE_ALIASES[service]?.[t] ?? t;
  for (const f of formatsOf(service)) if (f.re.test(resource)) return alias(f.type);
  const first = /^([A-Za-z][A-Za-z0-9-]*)[/:]/.exec(resource)?.[1]?.toLowerCase();
  return first !== undefined && literalTypeTokens(service).has(first) ? first : 'resource';
}

/** `arn:<partition>:<service>:<region>:<account>:<resource>` -> service, region and resource type. */
export function parseArn(arn: string): { service: string; region: string; type: string } | null {
  const parts = arn.split(':');
  if (parts.length < 6 || parts[0] !== 'arn') return null;
  const service = parts[2] as string;
  return { service, region: parts[3] as string, type: awsResourceType(service, parts.slice(5).join(':')) };
}
