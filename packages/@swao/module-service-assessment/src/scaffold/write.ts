/**
 * Scaffold writer (Design 103 §3.5, §4.1, §4.2, #3077, #3083).
 *
 * Writes one `apps/<id>/.swao.yml` per planned app (the existing per-app
 * config file, with `assessment.type: service`), the HINT ingestion folders,
 * `wsp/signals/scaffold-signals.json`, and the `service_portfolio:` block of
 * the workspace `.swao.yml`. Existing application apps are never touched; an
 * existing service app is only rewritten with `refresh`, and then only the
 * keys still listed in its `generated_fields`.
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { load as yamlLoad, dump as yamlDump } from 'js-yaml';
import { SCAFFOLD_SIGNAL_CODES, ScaffoldSignalsFileSchema, type ScaffoldSignal } from '@swao/core';
import type { AppPlan } from './plan.js';

/** Optional hint subfolders of `ingestion/` that are still honoured; no longer created (#3212). */
export const INGESTION_HINT_FOLDERS = ['contracts', 'security', 'certifications', 'binary', 'network', 'data-flow', 'manuals'] as const;
export const SERVICE_INPUT_FOLDERS = ['vendor', 'security', 'certifications', 'binary', 'research', 'network', 'data-flow'] as const;

export interface ServicePortfolioMeta {
  source: string;
  /** #3521: SHA-256 of the intake workbook; with `source` it identifies the intake generation. */
  source_sha256?: string;
  mapping: string | null;
  imported_at: string;
  app_count: number;
  row_count: number;
  sheets: string[];
  /** Header names per sheet, keyed by column letter (names only). */
  headers: Record<string, Record<string, string>>;
  pii_columns: string[];
  cluster_threshold: number;
}

export interface WriteResult {
  created: string[];
  refreshed: string[];
  skippedExisting: string[];
  /** App folders that hold a non-service app config; never overwritten. */
  conflicts: string[];
  /**
   * Existing service apps whose ID this intake no longer produces (rows removed,
   * or IDs changed by a newer parser, #3167). Never deleted; reported so the
   * workspace does not silently hold two generations of app folders.
   */
  notInIntake: string[];
  signalsFile: string;
}

const HEADER = (meta: ServicePortfolioMeta, p: AppPlan): string =>
  [
    '# .swao.yml -- SWAO app configuration (Service Portfolio Assessment)',
    `# Generated by: swao service init --from ${meta.source}`,
    `# Source: sheet "${p.config.intake.sheet}", row ${p.config.intake.row}`,
    '# Re-run `swao service init --refresh` to update from the intake file. Only keys',
    '# listed in generated_fields are rewritten; remove a key from that list to keep',
    '# a manual edit. PII columns are stored as presence booleans only.',
    '',
  ].join('\n');

function readYaml(path: string): Record<string, unknown> | null {
  try {
    const v = yamlLoad(readFileSync(path, 'utf-8'));
    return v && typeof v === 'object' ? (v as Record<string, unknown>) : null;
  } catch {
    return null;
  }
}

function dump(obj: unknown): string {
  return yamlDump(obj, { lineWidth: -1, noRefs: true, sortKeys: false });
}

/** Replace (or append) the top-level `service_portfolio:` block, keeping the rest of the file and its comments. */
export function upsertServicePortfolioBlock(text: string, meta: ServicePortfolioMeta): string {
  const lines = text.split(/\r?\n/);
  const start = lines.findIndex((l) => /^service_portfolio:\s*$/.test(l));
  // trimEnd() strips exactly what `/\s*$/` matched, without its polynomial backtracking.
  if (start < 0) return `${text.trimEnd()}\n\n${dump({ service_portfolio: meta }).trimEnd()}\n`;
  let end = start + 1;
  while (end < lines.length && (/^\s/.test(lines[end] as string) || (lines[end] as string) === '')) end++;
  // #3210: analyst-owned keys in the block (glossary, cost options) survive a
  // re-run; only the scaffold metadata keys are rewritten.
  const preserved: Record<string, unknown> = {};
  try {
    const old = (yamlLoad(lines.slice(start, end).join('\n')) as { service_portfolio?: Record<string, unknown> } | null)?.service_portfolio;
    if (old && typeof old === 'object') {
      for (const [k, v] of Object.entries(old)) if (!(k in meta)) preserved[k] = v;
    }
  } catch { /* unreadable block: rewrite metadata only */ }
  const block = dump({ service_portfolio: { ...meta, ...preserved } }).trimEnd();
  return [...lines.slice(0, start), block, ...lines.slice(end)].join('\n');
}

export function writeScaffold(
  workspacePath: string,
  apps: readonly AppPlan[],
  signals: readonly ScaffoldSignal[],
  meta: ServicePortfolioMeta,
  opts: { refresh?: boolean; warnings?: readonly string[] } = {},
): WriteResult {
  const result: WriteResult = { created: [], refreshed: [], skippedExisting: [], conflicts: [], notInIntake: [], signalsFile: '' };
  const planned = new Set(apps.map((p) => p.appId));
  const appsDir = join(workspacePath, 'apps');
  if (existsSync(appsDir)) {
    for (const id of readdirSync(appsDir).sort()) {
      if (planned.has(id)) continue;
      const doc = readYaml(join(appsDir, id, '.swao.yml'));
      if ((doc?.['assessment'] as { type?: unknown } | undefined)?.type === 'service') result.notInIntake.push(id);
    }
  }

  for (const p of apps) {
    const appDir = join(workspacePath, 'apps', p.appId);
    const ymlPath = join(appDir, '.swao.yml');
    let body: Record<string, unknown> = p.config as unknown as Record<string, unknown>;

    if (existsSync(ymlPath)) {
      const existing = readYaml(ymlPath);
      const type = (existing?.['assessment'] as { type?: unknown } | undefined)?.type;
      if (type !== 'service') {
        result.conflicts.push(p.appId);
        continue;
      }
      if (!opts.refresh) {
        result.skippedExisting.push(p.appId);
        continue;
      }
      const owned = Array.isArray(existing?.['generated_fields'])
        ? new Set((existing?.['generated_fields'] as unknown[]).filter((k): k is string => typeof k === 'string'))
        : new Set<string>(Object.keys(body));
      const merged: Record<string, unknown> = { ...existing };
      for (const [k, v] of Object.entries(body)) {
        if (k === 'assessment' && merged[k] && typeof merged[k] === 'object') {
          // Keep analyst-added keys (frameworks, lenses); the scaffold only owns the type.
          merged[k] = { ...(merged[k] as Record<string, unknown>), type: 'service' };
        } else if (k === 'generated_fields' || k === 'generated_at' || owned.has(k) || !(k in merged)) {
          merged[k] = v;
        }
      }
      merged['generated_fields'] = existing?.['generated_fields'] ?? body['generated_fields'];
      body = merged;
      result.refreshed.push(p.appId);
    } else {
      result.created.push(p.appId);
    }

    // #3212: only the drop folder; Pass 00 routes dropped files into wsp/inputs/<category>/
    // by content, and existing hint folders keep working. No empty folders per app.
    mkdirSync(join(appDir, 'ingestion'), { recursive: true });
    writeFileSync(ymlPath, HEADER(meta, p) + dump(body), 'utf-8');
  }

  // Workspace-level scaffold signals
  const counts: Record<string, number> = Object.fromEntries(SCAFFOLD_SIGNAL_CODES.map((c) => [c, 0]));
  for (const s of signals) counts[s.code] = (counts[s.code] ?? 0) + 1;
  const file = ScaffoldSignalsFileSchema.parse({
    generated_at: new Date().toISOString(),
    source: meta.source,
    counts,
    signals,
    warnings: opts.warnings ?? [],
  });
  const signalsDir = join(workspacePath, 'wsp', 'signals');
  mkdirSync(signalsDir, { recursive: true });
  result.signalsFile = join(signalsDir, 'scaffold-signals.json');
  writeFileSync(result.signalsFile, `${JSON.stringify(file, null, 2)}\n`, 'utf-8');

  // Workspace .swao.yml service_portfolio block
  const wsYml = join(workspacePath, '.swao.yml');
  const text = existsSync(wsYml) ? readFileSync(wsYml, 'utf-8') : '# .swao.yml -- SWAO workspace configuration\nwsp_version: "0.9"\n';
  writeFileSync(wsYml, upsertServicePortfolioBlock(text, meta), 'utf-8');

  return result;
}
